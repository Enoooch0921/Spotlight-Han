import AppKit

@MainActor
final class ClipboardHistory {
    private var timer: Timer?
    private var changeCount = NSPasteboard.general.changeCount
    var changed: ((String) -> Void)?
    func start() {
        stop()
        changeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }
    func stop() { timer?.invalidate(); timer = nil }
    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        let types = pasteboard.types ?? []
        guard !types.contains(NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")),
              !types.contains(NSPasteboard.PasteboardType("org.nspasteboard.TransientType")),
              !types.contains(NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")),
              let value = pasteboard.string(forType: .string), !value.isEmpty, value.count <= 2000 else { return }
        // Common password managers additionally get excluded even if a copy has no conceal flag.
        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier?.lowercased() ?? ""
        guard !["1password", "onepassword", "bitwarden", "keepass", "lastpass"].contains(where: app.contains) else { return }
        changed?(value)
    }
    deinit { timer?.invalidate() }
}
